"""Motor A USD inflation-factor vintage bridge guards (all synthetic inputs).

Real post-release bytes are checked only by the separate GitHub Actions
original-archive E2E workflow, never generated by these unit tests.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from tempfile import TemporaryDirectory
from unittest.mock import patch
import unittest

from atlasquant_trader_fx28_32_factor_source_admission_lab import (
    inspect_fx28_32_factor_source_admission_lab as inspect,
)
from atlasquant_trader_us_ppi_sep2026_two_real_vintages_lab import (
    SEP_HASH, OCT_HASH, SEP_CAPTURE, OCT_CAPTURE, _blocked as revision_blocked,
)

UTC = timezone.utc
NOW = SEP_CAPTURE + timedelta(days=1)
BAD = (b"X" * 120_000, b"Y" * 120_000)


def synthetic_success_vintage_claim():
    """ALWAYS a mock: not a verified BLS record, a price or a forecast."""
    report = revision_blocked("MOCK_DOCUMENTARY_OUTCOME", visible=2)
    report.update({
        "state": "LAB_PPI_SEP2026_TWO_REAL_VINTAGES_RECONCILED_NO_GO",
        "reason": "REAL_POSTRELEASE_ORIGINALS_SHOW_PRIOR_MONTH_REVISION_NOT_FORECAST",
        "originals_visible_at_local_cutoff": 2,
        "original_sep_release_visible": True,
        "oct_release_with_sep_revision_visible": True,
        "sep_reported_sep2026_sa_mom_headline_pct": "1.3",
        "sep_reported_sep2026_sa_mom_core_ex_food_energy_pct": "0.7",
        "oct_reported_revised_sep2026_sa_mom_headline_pct": "1.4",
        "oct_reported_revised_sep2026_sa_mom_core_ex_food_energy_pct": "0.8",
        "later_revision_minus_first_release_headline_pp": "0.1",
        "later_revision_minus_first_release_core_pp": "0.1",
        "original_sep_release_html_sha256": SEP_HASH,
        "oct_release_html_sha256": OCT_HASH,
    })
    return report


class VintageJoinToMotorATests(unittest.TestCase):
    def setUp(self):
        self.tmp = TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def run_join(self, *, vintage=None, now=NOW):
        return inspect(
            local_appdata=self.tmp.name, decision_at_utc=now,
            ppi_sep2026_two_vintage_originals=vintage,
        )

    def safe(self, report):
        self.assertEqual(report["operational_bias"], "AGUARDAR")
        self.assertFalse(report["trade_authorized"])
        self.assertFalse(report["publishable"])
        self.assertFalse(report["real_directional_forecast_authorized"])
        self.assertFalse(report["experimental_score_execution_authorized"])
        self.assertFalse(report["historical_macro_point_in_time_authenticated"])
        self.assertFalse(report["model_directional_effects_calibrated"])
        self.assertEqual(report["factor_slots_with_signed_impact_independently_admissible"], 0)
        self.assertEqual(report["factor_slots_with_pre_event_consensus_verified"], 0)
        self.assertEqual(report["factor_slots_with_calibrated_directional_effect"], 0)
        self.assertIsNone(report["calibrated_probability"])
        self.assertIsNone(report["validated_direction_accuracy"])
        self.assertEqual(report["network_requests"], 0)
        self.assertEqual(report["file_writes"], 0)
        self.assertTrue(report["ppi_sep2026_revision_never_backfilled_to_october_decision"])

    def test_01_default_admission_preserved_no_new_vintage(self):
        report = self.run_join()
        self.safe(report)
        self.assertEqual(report["state"],
                         "LAB_FX28_32_FACTOR_DOCUMENTARY_GAP_RECONCILED_NO_GO")
        self.assertEqual(report["factor_slots_inspected"], 32)
        self.assertEqual(len(report["pairs"]), 28)
        self.assertFalse(report["ppi_sep2026_vintage_context_requested"])
        self.assertEqual(report["ppi_sep2026_verified_original_count_at_local_cutoff"], 0)
        self.assertIsNone(report["ppi_sep2026_vintage_research_context"])

    def test_02_malformed_vintage_inputs_fail_closed_before_replay(self):
        for bad in ([], [b"a", b"b"], (), (b"a",), "raw",
                    (b"x"*120_000, "text"), (None, None)):
            with self.subTest(vintage=type(bad)):
                out=self.run_join(vintage=bad)
                self.safe(out)
                self.assertEqual(out["state"],
                                 "LAB_FX28_32_FACTOR_ADMISSION_BLOCKED_NO_GO")

    def test_03_input_unbounded_payload_rejected(self):
        out=self.run_join(vintage=(b"x"*4_194_305, b"y"*120_000))
        self.safe(out)
        self.assertEqual(out["factor_slots_inspected"],0)

    def test_04_future_two_bytes_cannot_appear_before_first_capture(self):
        # PIT hides originals even if caller supplies invented future bytes.
        out=self.run_join(vintage=BAD,
                          now=OCT_CAPTURE-timedelta(seconds=1))
        self.safe(out)
        self.assertEqual(out["state"],
                         "LAB_FX28_32_FACTOR_DOCUMENTARY_GAP_RECONCILED_NO_GO")
        self.assertTrue(out["ppi_sep2026_vintage_context_requested"])
        self.assertEqual(out["ppi_sep2026_verified_original_count_at_local_cutoff"],0)
        self.assertIsNone(out["ppi_sep2026_vintage_research_context"])

    def test_05_fake_oct_original_at_its_capture_time_vetoes_all(self):
        out=self.run_join(vintage=BAD,now=OCT_CAPTURE)
        self.safe(out)
        self.assertEqual(out["state"],
                         "LAB_FX28_32_FACTOR_ADMISSION_BLOCKED_NO_GO")
        self.assertEqual(out["factor_slots_inspected"],0)

    def test_06_fake_both_origins_at_last_capture_vetoes_all(self):
        out=self.run_join(vintage=BAD,now=SEP_CAPTURE)
        self.safe(out)
        self.assertEqual(out["factor_slots_inspected"],0)
        self.assertIsNone(out["ppi_sep2026_vintage_research_context"])

    def test_07_successful_mock_bridge_never_adds_signed_factor(self):
        with patch(
            "atlasquant_trader_fx28_32_factor_source_admission_lab."
            "inspect_real_ppi_sep2026_release_vintages_lab",
            return_value=synthetic_success_vintage_claim(),
        ) as p:
            out=self.run_join(vintage=BAD)
        p.assert_called_once()
        self.safe(out)
        self.assertTrue(out["ppi_sep2026_first_release_and_revision_reconciled_local_only"])
        self.assertEqual(out["ppi_sep2026_verified_original_count_at_local_cutoff"],2)
        self.assertEqual(out["factor_slots_inspected"],32)
        self.assertEqual(len(out["pairs"]),28)
        self.assertEqual(out["factor_slots_with_any_relevant_local_document"],0)

    def test_08_revision_attached_exactly_once_to_usd_inflation_factor(self):
        with patch(
            "atlasquant_trader_fx28_32_factor_source_admission_lab."
            "inspect_real_ppi_sep2026_release_vintages_lab",
            return_value=synthetic_success_vintage_claim(),
        ):
            out=self.run_join(vintage=BAD)
        self.safe(out)
        attached=[s for s in out["factor_slots"] if
                  s["ppi_sep2026_historical_two_release_revision_context"] is not None]
        self.assertEqual(len(attached),1)
        self.assertEqual((attached[0]["currency"],attached[0]["category"]),
                         ("USD","inflation_impact"))
        ctx=attached[0]["ppi_sep2026_historical_two_release_revision_context"]
        self.assertEqual(ctx["reference_period"],"2026-09")
        self.assertEqual(ctx["initial_release"]["headline_pct"],"1.3")
        self.assertEqual(ctx["later_release_revision"]["headline_pct"],"1.4")
        self.assertEqual(ctx["initial_release"]["core_ex_food_energy_pct"],"0.7")
        self.assertEqual(ctx["later_release_revision"]["core_ex_food_energy_pct"],"0.8")
        self.assertFalse(ctx["can_derive_signed_inflation_impact"])
        self.assertFalse(ctx["backtest_as_if_2026_10_15_known"])
        self.assertTrue(all(pair["forecast_direction"] is None for pair in out["pairs"]))

    def test_09_mock_with_forged_forex_score_vetoes_before_join(self):
        claim=synthetic_success_vintage_claim()
        claim["trade_authorized"]=True
        with patch(
            "atlasquant_trader_fx28_32_factor_source_admission_lab."
            "inspect_real_ppi_sep2026_release_vintages_lab",
            return_value=claim,
        ):
            out=self.run_join(vintage=BAD)
        self.safe(out)
        self.assertEqual(out["factor_slots_inspected"],0)

    def test_10_mock_with_wrong_revision_number_vetoes(self):
        claim=synthetic_success_vintage_claim()
        claim["oct_reported_revised_sep2026_sa_mom_core_ex_food_energy_pct"]="0.9"
        with patch(
            "atlasquant_trader_fx28_32_factor_source_admission_lab."
            "inspect_real_ppi_sep2026_release_vintages_lab",
            return_value=claim,
        ):
            out=self.run_join(vintage=BAD)
        self.safe(out)
        self.assertEqual(out["factor_slots_inspected"],0)

    def test_11_mock_with_nonmatching_document_sha_vetoes(self):
        claim=synthetic_success_vintage_claim()
        claim["original_sep_release_html_sha256"]="0"*64
        with patch(
            "atlasquant_trader_fx28_32_factor_source_admission_lab."
            "inspect_real_ppi_sep2026_release_vintages_lab",
            return_value=claim,
        ):
            out=self.run_join(vintage=BAD)
        self.safe(out)
        self.assertEqual(out["factor_slots_inspected"],0)

    def test_12_mock_with_partial_status_count_two_vetoes(self):
        claim=synthetic_success_vintage_claim()
        claim["state"]="LAB_PPI_SEP2026_REAL_RELEASE_VINTAGE_REPLAY_HARD_NO_GO"
        claim["reason"]="ONE_OR_BOTH_ORIGINALS_NOT_YET_CAPTURED_AT_LOCAL_CUTOFF"
        with patch(
            "atlasquant_trader_fx28_32_factor_source_admission_lab."
            "inspect_real_ppi_sep2026_release_vintages_lab",
            return_value=claim,
        ):
            out=self.run_join(vintage=BAD)
        self.safe(out)
        self.assertEqual(out["factor_slots_inspected"],0)

    def test_13_caller_cannot_pass_future_cutoff_microsecond(self):
        out=self.run_join(vintage=BAD,now=NOW+timedelta(microseconds=1))
        self.safe(out)
        self.assertEqual(out["factor_slots_inspected"],0)

    def test_14_live_broker_and_fx28_are_never_called_for_vintage(self):
        with patch(
            "atlasquant_trader_fx28_32_factor_source_admission_lab."
            "inspect_real_ppi_sep2026_release_vintages_lab",
            return_value=synthetic_success_vintage_claim(),
        ):
            out=self.run_join(vintage=BAD)
        self.safe(out)
        self.assertEqual(out["new_cost_brl"],0)
        self.assertFalse(out["fx28_forecast_witnessed_before_window"])
        self.assertTrue(all(p["model_signed_factor_slots_admitted"]==0
                            and p["trade_authorized"] is False
                            for p in out["pairs"]))


if __name__ == "__main__":
    unittest.main()

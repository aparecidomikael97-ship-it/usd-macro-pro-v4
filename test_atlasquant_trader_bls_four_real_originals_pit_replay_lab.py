    def test_24_tampered_parser_result_cannot_add_new_actual(self):
        # A future parser must not be allowed to claim an arbitrary success
        # with a count/sha that differs from the verified source snapshot.
        original=m.inspect_four_bls_original_documentary_events_lab
        def corrupted(*,source_claims,research_cutoff_utc):
            good=original(source_claims=source_claims,
                          research_cutoff_utc=research_cutoff_utc)
            good["events"][0]["original_sha256"]="0"*64
            return good
        with patch.object(m,"inspect_four_bls_original_documentary_events_lab",
                          side_effect=corrupted):
            r=self.run_at(datetime(2026,11,16,3,tzinfo=UTC))
        self.assertEqual(r["reason"],"BLS_SOURCE_BODY_OR_CUTOFF_SEMANTICS_MISMATCH")


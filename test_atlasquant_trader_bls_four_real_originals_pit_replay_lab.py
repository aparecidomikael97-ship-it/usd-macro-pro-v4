    def test_27_invalid_receipt_html_mime_is_rejected_pre_parser(self):
        fake=FakeNestedArchive(self.archive.path)
        # All existing fake receipts are valid, but forcing non-HTML status
        # while recomputing pinned hashes must still fail closed. See the
        # preexisting SHA tamper tests for byte-level mismatch cases.
        with ZipFile(fake.path) as z:
            names={name:z.read(name) for name in z.namelist()}
        path=fake.archives["oct_cpi"][0]
        with ZipFile(BytesIO(names[path])) as z:
            nested={name:z.read(name) for name in z.namelist()}
        receipt_name=fake.pins["US_CPI_OCT2026"][2]
        receipt=json.loads(nested[receipt_name].decode())
        receipt["content_type"]="text/plain"
        nested[receipt_name]=json.dumps(receipt).encode()
        fake.pins["US_CPI_OCT2026"]=(*fake.pins["US_CPI_OCT2026"][:4],
                                   h(nested[receipt_name]),
                                   *fake.pins["US_CPI_OCT2026"][5:])
        names[path]=encode_zip(nested)
        fake.archives["oct_cpi"]=(path,h(names[path]))
        fake.manifest["actions_archives"]=[
            {**x,"zip_sha256":h(names[x["zip_path"]])}
            for x in fake.manifest["actions_archives"]
        ]
        names["manifesto_sha256.json"]=json.dumps(fake.manifest).encode()
        fake.path.write_bytes(encode_zip(names))
        with patch.object(m,"PINS",fake.pins),patch.object(m,"ARCHIVES",fake.archives):
            r=self.run_at(datetime(2026,11,16,3,tzinfo=UTC))
        self.assertEqual(r["reason"],"RECEIPT_SOURCE_IDENTITY_OR_CAPTURE_INVALID")


